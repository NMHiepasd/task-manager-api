import http from 'k6/http';
import { check, sleep, group } from 'k6';
import { Trend, Rate, Counter } from 'k6/metrics';

// Custom metrics for performance evaluation
const loginDuration = new Trend('login_duration_ms');
const listTasksDuration = new Trend('list_tasks_duration_ms');
const createTaskDuration = new Trend('create_task_duration_ms');
const cacheReadDuration = new Trend('cache_read_duration_ms');
const errorRate = new Rate('api_errors');
const tasksCreated = new Counter('tasks_created_total');

// Configuration options
export const options = {
  stages: [
    { duration: '10s', target: 10 },  // Ramp-up to 10 VUs
    { duration: '20s', target: 25 },  // Sustained load at 25 VUs
    { duration: '10s', target: 0 },   // Graceful ramp-down to 0 VUs
  ],
  thresholds: {
    http_req_duration: ['p(95)<200', 'p(99)<500'], // 95% of requests must complete within 200ms
    http_req_failed: ['rate<0.01'],                 // Error rate below 1%
    api_errors: ['rate<0.01'],
  },
};

const BASE_URL = __ENV.API_URL || 'http://localhost:8080';

// Helper to generate unique string per VU and iteration
function uniqueId() {
  return `${__VU}_${__ITER}_${Date.now()}`;
}

export function setup() {
  // Check health and readiness before beginning benchmark
  const healthRes = http.get(`${BASE_URL}/healthz`);
  check(healthRes, {
    'Healthz responds with 200': (r) => r.status === 200,
  });

  const readyRes = http.get(`${BASE_URL}/readyz`);
  check(readyRes, {
    'Readyz responds with 200': (r) => r.status === 200,
  });

  // Pre-authenticate a dedicated benchmark user in setup
  const userEmail = 'k6_bench_user@example.com';
  const userPassword = 'Password123!';
  const registerPayload = JSON.stringify({
    email: userEmail,
    password: userPassword,
    full_name: 'K6 Benchmark User',
  });
  const headers = { 'Content-Type': 'application/json' };

  http.post(`${BASE_URL}/api/v1/auth/register`, registerPayload, { headers });

  const loginRes = http.post(`${BASE_URL}/api/v1/auth/login`, JSON.stringify({
    email: userEmail,
    password: userPassword,
  }), { headers });

  const token = loginRes.json('access_token');
  if (!token) {
    console.error(`[k6 setup] Login failed! Status: ${loginRes.status}, Body: ${loginRes.body}`);
  }
  return { baseUrl: BASE_URL, token: token };
}

export default function (data) {
  const baseUrl = data.baseUrl;
  const token = data.token;

  if (!token) {
    errorRate.add(1);
    sleep(1);
    return;
  }

  const authHeaders = {
    'Content-Type': 'application/json',
    'Authorization': `Bearer ${token}`,
  };

  // 1. Cache-Aside Reading Flow (Tags list with ETag validation)
  group('Cached Data Retrieval', function () {
    const startCache = Date.now();
    const tagsRes = http.get(`${baseUrl}/api/v1/tags`, { headers: authHeaders });
    cacheReadDuration.add(Date.now() - startCache);

    check(tagsRes, {
      'List tags status is 200': (r) => r.status === 200,
      'Response has ETag header': (r) => r.headers['Etag'] !== undefined || r.headers['ETag'] !== undefined,
    });

    // Test 304 Not Modified when sending If-None-Match
    const etag = tagsRes.headers['Etag'] || tagsRes.headers['ETag'];
    if (etag) {
      const ifNoneMatchHeaders = Object.assign({}, authHeaders, { 'If-None-Match': etag });
      const notModifiedRes = http.get(`${baseUrl}/api/v1/tags`, { headers: ifNoneMatchHeaders });
      check(notModifiedRes, {
        'If-None-Match returns 304 Not Modified': (r) => r.status === 304,
      });
    }
  });

  // 2. Task Creation with Idempotency Key
  group('Create Task Flow', function () {
    const idempotencyKey = `k6_idemp_${uniqueId()}`;
    const taskPayload = JSON.stringify({
      title: `K6 Automated Task ${uniqueId()}`,
      description: 'Performance testing benchmark task generated by k6',
      status: 'todo',
      priority: 'high',
    });

    const postHeaders = Object.assign({}, authHeaders, {
      'Idempotency-Key': idempotencyKey,
    });

    const startCreate = Date.now();
    const createRes = http.post(`${baseUrl}/api/v1/tasks`, taskPayload, { headers: postHeaders });
    createTaskDuration.add(Date.now() - startCreate);

    const createSuccess = check(createRes, {
      'Create task returns 201': (r) => r.status === 201,
      'Created task has valid UUID': (r) => r.json('id') !== undefined,
    });

    if (createSuccess) {
      tasksCreated.add(1);
    } else {
      errorRate.add(1);
    }
  });

  // 3. Keyset Pagination Task Listing
  group('List Tasks Keyset Pagination', function () {
    const startList = Date.now();
    const listRes = http.get(`${baseUrl}/api/v1/tasks?limit=20`, { headers: authHeaders });
    listTasksDuration.add(Date.now() - startList);

    check(listRes, {
      'List tasks returns 200': (r) => r.status === 200,
      'List tasks contains items array': (r) => Array.isArray(r.json('items')),
    });
  });

  sleep(0.5); // Short think time between iterations
}
